const dictionaries: Record<AppLocale, Record<string, string>> = {
  "zh-CN": {},
  "en-US": enUS,
};

export function setLocale(value: AppLocale) {
  locale.value = value;
  if (typeof document !== "undefined") document.documentElement.lang = value;
}

export function translate(key: string, params: TranslationParams = {}) {
  const template = dictionaries[locale.value][key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match,
  );
}

export function useI18n() {
  return { locale: readonly(locale), t: translate };
}
